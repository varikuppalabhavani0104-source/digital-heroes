-- settings: anyone reads (pricing page), admin edits
create policy settings_read  on app_settings for select using (true);
create policy settings_admin on app_settings for update using (is_admin()) with check (is_admin());

-- charities: public directory, admin CRUD
create policy charities_read  on charities for select using (is_active or is_admin());
create policy charities_admin on charities for all using (is_admin()) with check (is_admin());
create policy events_read     on charity_events for select using (true);
create policy events_admin    on charity_events for all using (is_admin()) with check (is_admin());

-- profiles: own row (role change blocked by trigger) + admin
create policy profiles_self_read   on profiles for select using (id = auth.uid() or is_admin());
create policy profiles_self_update on profiles for update using (id = auth.uid() or is_admin());

-- subscriptions / contributions / donations: read own; writes via service role only
create policy subs_read   on subscriptions         for select using (user_id = auth.uid() or is_admin());
create policy subs_admin  on subscriptions         for update using (is_admin());
create policy contrib_read on charity_contributions for select using (user_id = auth.uid() or is_admin());
create policy donations_read on donations           for select using (user_id = auth.uid() or is_admin());

-- scores: users manage own scores ONLY while subscribed; admin manages all
create policy scores_read   on scores for select using (user_id = auth.uid() or is_admin());
create policy scores_insert on scores for insert with check (
  (user_id = auth.uid() and has_active_subscription()) or is_admin());
create policy scores_update on scores for update using (
  (user_id = auth.uid() and has_active_subscription()) or is_admin());
create policy scores_delete on scores for delete using (
  (user_id = auth.uid() and has_active_subscription()) or is_admin());

-- draws: published draws are public (landing page "latest draw"); admin sees all
create policy draws_read  on draws for select using (status = 'published' or is_admin());
create policy draws_admin on draws for all using (is_admin()) with check (is_admin());

-- entries / winners: users see only their own, and only for published draws
create policy entries_read on draw_entries for select using (
  is_admin() or (user_id = auth.uid() and exists (select 1 from draws d where d.id = draw_id and d.status = 'published')));
create policy entries_admin on draw_entries for all using (is_admin()) with check (is_admin());
create policy winners_read  on winners for select using (user_id = auth.uid() or is_admin());
create policy winners_admin on winners for all using (is_admin()) with check (is_admin());

